"""Run the prototype against QA's 50 synthetic emails and measure it.

Covers: AC-1, IN-04, IN-08, IN-09, PR-01

Usage, from the repository root:
    python3 spikes/document_understanding/evaluate.py            # QA's 50 fixture emails
    python3 spikes/document_understanding/evaluate.py --holdout  # the 16 hold out emails

Writes results/report.md (or results/holdout.md) and a JSON file next to it.
"""

from __future__ import annotations

import csv
import json
import sys
import time
from pathlib import Path

HERE = Path(__file__).resolve().parent
sys.path.insert(0, str(HERE))

from classify import Config, classify  # noqa: E402
from documents import read_email  # noqa: E402

ROOT = HERE.parents[1]
FIXTURES = ROOT / "tests" / "fixtures"

FIELDS = (
    "issuer_name", "recipient_name", "vendor_vat_id", "invoice_number", "invoice_date", "service_period",
    "net_amount", "vat_rate", "vat_amount", "gross_amount", "currency", "due_date",
    "early_payment_discount", "iban_on_document", "direct_debit", "refers_to",
)


def run(email_dir: Path = FIXTURES / "emails") -> dict:
    config = Config.from_master_data(FIXTURES / "master-data")
    expected_docs = {d["document_id"]: d for d in json.loads((FIXTURES / "documents" / "expected.json").read_text())}
    with (email_dir / "manifest.csv").open(encoding="utf-8") as f:
        manifest = list(csv.DictReader(f))

    rows, field_checks = [], []
    for item in manifest:
        started = time.perf_counter()
        mail = read_email(email_dir / item["file"])
        decision = classify(mail, config)
        seconds = time.perf_counter() - started

        rows.append({
            "email_id": item["email_id"],
            "expected_route": item["expected_route"],
            "route": decision.route,
            "route_ok": decision.route == item["expected_route"],
            "expected_cases": int(item["invoice_count"]),
            "cases": len(decision.cases),
            "cases_ok": len(decision.cases) == int(item["invoice_count"]),
            "proposed": decision.proposed,
            "confidence": decision.confidence,
            "gates": decision.gates,
            "evidence": decision.evidence,
            "seconds": round(seconds, 2),
        })

        # Field accuracy (PR-01): match each expected document to the case with the same number.
        by_number = {c.fields.get("invoice_number"): c for c in decision.cases}
        for doc_id in item.get("documents", "").split():
            exp = expected_docs[doc_id]
            case = by_number.get(exp["invoice_number"])
            for name in FIELDS:
                got = case.fields.get(name) if case else None
                want = exp.get(name)
                if name == "early_payment_discount" and isinstance(got, dict):
                    got = {"percent": got.get("percent"), "until": got.get("until")}
                field_checks.append({
                    "email_id": item["email_id"], "document_id": doc_id, "format": exp["format"],
                    "field": name, "ok": got == want, "got": got, "want": want,
                })

    return summarise(rows, field_checks)


def summarise(rows: list[dict], field_checks: list[dict]) -> dict:
    correct = sum(r["route_ok"] for r in rows)
    lost = [r["email_id"] for r in rows
            if r["route"] == "deletion_folder" and r["expected_route"] in ("invoice_processing", "outgoing_booking", "manual_review")]
    by_format: dict[str, list[bool]] = {}
    for c in field_checks:
        by_format.setdefault(c["format"], []).append(c["ok"])
    return {
        "emails": len(rows),
        "routes_correct": correct,
        "route_accuracy": round(correct / len(rows), 3),
        "ac1_passed": correct / len(rows) >= 0.95,
        "invoices_sent_to_deletion": lost,
        "cases_correct": sum(r["cases_ok"] for r in rows),
        "fields_checked": len(field_checks),
        "fields_correct": sum(c["ok"] for c in field_checks),
        "field_accuracy_by_format": {k: f"{sum(v)}/{len(v)}" for k, v in sorted(by_format.items())},
        "field_errors": [c for c in field_checks if not c["ok"]],
        "seconds_total": round(sum(r["seconds"] for r in rows), 1),
        "rows": rows,
    }


def write_report(result: dict, title: str, command: str) -> str:
    lines = [
        f"# {title}",
        "",
        f"Generated by `{command}`. Do not edit by hand.",
        "",
        f"- Routes correct: **{result['routes_correct']} of {result['emails']}** ({result['route_accuracy']:.0%}). AC-1 needs 95 %.",
        f"- Invoices sent to the deletion folder: **{len(result['invoices_sent_to_deletion'])}** {result['invoices_sent_to_deletion'] or ''}",
        f"- Emails split into the right number of cases (IN-08): **{result['cases_correct']} of {result['emails']}**",
        (f"- PR-01 fields correct: **{result['fields_correct']} of {result['fields_checked']}**, by format: "
         + ", ".join(f"{k} {v}" for k, v in result["field_accuracy_by_format"].items())) if result["fields_checked"] else
        "- PR-01 fields: not measured on this set",
        f"- Run time for all {result['emails']} emails: {result['seconds_total']} s on one CPU, OCR included",
        "",
        "| Email | Expected | ARGUS | Points said | Confidence | Why it went to manual review |",
        "|---|---|---|---|---|---|",
    ]
    for r in result["rows"]:
        mark = "" if r["route_ok"] else " ❌"
        gates = "<br>".join(r["gates"]) if r["route"] == "manual_review" else ""
        cases = "" if r["cases_ok"] else f" (cases {r['cases']}, expected {r['expected_cases']})"
        lines.append(f"| {r['email_id']} | {r['expected_route']} | {r['route']}{mark}{cases} | {r['proposed']} | {r['confidence']:.2f} | {gates} |")
    if result["field_errors"]:
        lines += ["", "## Field errors", "", "| Email | Document | Field | Expected | Got |", "|---|---|---|---|---|"]
        for c in result["field_errors"]:
            lines.append(f"| {c['email_id']} | {c['document_id']} | {c['field']} | {c['want']} | {c['got']} |")
    return "\n".join(lines) + "\n"


if __name__ == "__main__":
    holdout = "--holdout" in sys.argv
    if holdout:
        result = run(HERE / "holdout" / "emails")
        name, title = "holdout", "Prototype run against the 16 hold out emails"
        command = "python3 spikes/document_understanding/evaluate.py --holdout"
    else:
        result = run()
        name, title = "report", "Prototype run against the 50 synthetic emails"
        command = "python3 spikes/document_understanding/evaluate.py"
    out = HERE / "results"
    out.mkdir(exist_ok=True)
    (out / f"{name}.json").write_text(json.dumps(result, indent=2, ensure_ascii=False, default=str) + "\n")
    report = write_report(result, title, command)
    (out / f"{name}.md").write_text(report)
    print(report)
